"""Authenticated mood and progress dashboard endpoints."""

from __future__ import annotations

import datetime
from typing import Any

from fastapi import APIRouter, Depends, Query
from motor.motor_asyncio import AsyncIOMotorDatabase

from app.db import get_db
from app.middleware.auth import require_user
from app.services.progress import generate_progress_insight
from app.utils.logger import get_logger

logger = get_logger(__name__)

router = APIRouter()

# services/progress.py generates the weekly insight. design.md §4.2 gates
# the insight card on >= 7 sessions, and the insight is refreshed every 7
# sessions rather than on every dashboard visit.
MIN_SESSIONS_FOR_INSIGHT = 7
REGENERATE_EVERY_N_SESSIONS = 7


@router.get("/mood")
async def get_mood_logs(
    limit: int = Query(default=30, ge=1, le=90),
    db: AsyncIOMotorDatabase = Depends(get_db),
    current_user: dict[str, Any] = Depends(require_user),
) -> dict[str, list[dict[str, Any]]]:
    user_id = str(current_user["_id"])
    cursor = (
        db.mood_logs.find({"user_id": user_id}, {"_id": 0})
        .sort("timestamp", -1)
        .limit(limit)
    )
    return {"moods": await cursor.to_list(length=limit)}


@router.get("/summary")
async def get_dashboard_summary(
    db: AsyncIOMotorDatabase = Depends(get_db),
    current_user: dict[str, Any] = Depends(require_user),
) -> dict[str, Any]:
    user_id = str(current_user["_id"])
    session_count = await db.sessions.count_documents({"user_id": user_id})
    memory = await db.user_memory.find_one({"user_id": user_id}, {"_id": 0})
    latest_moods = await (
        db.mood_logs.find({"user_id": user_id}, {"_id": 0})
        .sort("timestamp", -1)
        .limit(7)
        .to_list(length=7)
    )
    return {
        "session_count": session_count,
        "latest_moods": latest_moods,
        "memory_enabled": memory is not None,
    }


@router.get("/insight")
async def get_progress_insight(
    db: AsyncIOMotorDatabase = Depends(get_db),
    current_user: dict[str, Any] = Depends(require_user),
) -> dict[str, Any]:
    """
    Weekly progress insight — design.md §4.2's "Weekly insight card (only
    with >= 7 sessions)".

    The insight itself is generated by ``services/progress.py``; this router
    owns the two things that are request-shaped: the >= 7-session gate and
    the cache, so the Progress tab does not spend an LLM call on every visit.
    The insight is refreshed once every 7 sessions — the cadence the V1
    progress agent documented — and the cached text is returned in between.
    """
    user_id = str(current_user["_id"])
    session_count = await db.sessions.count_documents({"user_id": user_id})

    if session_count < MIN_SESSIONS_FOR_INSIGHT:
        return {
            "available": False,
            "session_count": session_count,
            "sessions_needed": MIN_SESSIONS_FOR_INSIGHT - session_count,
        }

    cached = await db.progress_insights.find_one({"user_id": user_id})
    if cached and (
        session_count - cached.get("session_count_at_generation", 0)
        < REGENERATE_EVERY_N_SESSIONS
    ):
        return {
            "available": True,
            "insight": cached["insight"],
            "generated_at": cached["generated_at"],
            "session_count": session_count,
        }

    user = await db.users.find_one({"_id": current_user["_id"]}) or current_user
    user_name = user.get("nickname") or user.get("name") or "friend"
    age_group_raw = user.get("age_group", "adult")
    age_group = age_group_raw if age_group_raw in ("teen", "adult") else "adult"

    recent_moods = await (
        db.mood_logs.find({"user_id": user_id}, {"_id": 0})
        .sort("timestamp", -1)
        .limit(7)
        .to_list(length=7)
    )

    avg_distress = (
        sum(m.get("distress_level") or 0.0 for m in recent_moods) / len(recent_moods)
        if recent_moods
        else 0.4
    )
    latest_emotion = recent_moods[0].get("surface_emotion") if recent_moods else None

    # The progress prompt reads a list of past emotions; shape the mood-log
    # history to match rather than changing the prompt's contract.
    session_history = [
        {"emotion": m.get("surface_emotion", "unknown")} for m in reversed(recent_moods)
    ]

    try:
        insight = await generate_progress_insight(
            user_name=user_name,
            age_group=age_group,
            surface_emotion=latest_emotion or "neutral",
            distress_level=round(avg_distress, 3),
            session_history=session_history,
        )
    except Exception:
        logger.exception("Progress insight generation failed for user %s", user_id)
        return {
            "available": True,
            "insight": None,
            "session_count": session_count,
            "error": "Could not generate an insight right now. Try again shortly.",
        }

    now = datetime.datetime.now(datetime.UTC)
    await db.progress_insights.update_one(
        {"user_id": user_id},
        {
            "$set": {
                "insight": insight,
                "generated_at": now,
                "session_count_at_generation": session_count,
            }
        },
        upsert=True,
    )

    return {
        "available": True,
        "insight": insight,
        "generated_at": now,
        "session_count": session_count,
    }
